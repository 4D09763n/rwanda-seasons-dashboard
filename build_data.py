"""
build_data.py  -  Rwanda Seasons, Rainfall & Disaster Dashboard (MSAR)

What it does
  1. Reads the official World Bank CSV (rwanda-monthly-rainfall-1991-2020.csv)
  2. Checks that the data is complete and sensible
  3. Calculates simple statistics (wettest/driest month, season averages)
  4. Writes data.js, which the website reads

How to run (Python 3, no extra packages needed):
  python build_data.py
"""
import csv
import sys
from pathlib import Path

HERE = Path(__file__).parent
CSV_FILE = HERE / "rwanda-monthly-rainfall-1991-2020.csv"
OUT_FILE = HERE / "data.js"

PERIOD = "1991-2020"
RETRIEVED = "November 2026"               # change when you download new data
PORTAL_ANNUAL_MM = 1170.2                 # annual figure printed on the portal
SOURCE = ("World Bank Climate Change Knowledge Portal, Climatology (CRU), observed data "
          "from the Climatic Research Unit, University of East Anglia")
SOURCE_URL = "https://climateknowledgeportal.worldbank.org/country/rwanda/climate-data-historical"

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

# Seasons follow Meteo Rwanda (short rains = Sep-Dec). Edit here if needed.
SEASONS = [
    ("long-rains",  "Long rainy season",  "Itumba",   ["Mar", "Apr", "May"],            "rainy", "Main rainy season of the year."),
    ("long-dry",    "Long dry season",    "Impeshyi", ["Jun", "Jul", "Aug"],            "dry",   "Driest part of the year."),
    ("short-rains", "Short rainy season", "Umuhindo", ["Sep", "Oct", "Nov", "Dec"],     "rainy", "Second rainy season (Sep-Dec, as used by Meteo Rwanda)."),
    ("short-dry",   "Short dry season",   "Urugaryi", ["Jan", "Feb"],                   "dry",   "Shorter dry period (the World Bank portal counts Dec-Feb)."),
]
FULL = {"Jan": "January", "Feb": "February", "Mar": "March", "Apr": "April", "May": "May", "Jun": "June",
        "Jul": "July", "Aug": "August", "Sep": "September", "Oct": "October", "Nov": "November", "Dec": "December"}


def read_rainfall():
    rows = []
    with open(CSV_FILE, newline="", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            rows.append((r["Category"].strip(), float(r["Precipitation (mm)"])))
    return rows


def check(rows):
    months = [m for m, _ in rows]
    if months != MONTHS:
        sys.exit(f"ERROR: months are not Jan..Dec in order: {months}")
    if any(mm < 0 for _, mm in rows):
        sys.exit("ERROR: negative rainfall found")
    total = sum(mm for _, mm in rows)
    diff = abs(total - PORTAL_ANNUAL_MM) / PORTAL_ANNUAL_MM * 100
    if diff > 3:
        sys.exit(f"ERROR: monthly sum {total:.1f} mm is {diff:.1f}% away from the portal's {PORTAL_ANNUAL_MM} mm")
    return total, diff


def main():
    rows = read_rainfall()
    total, diff = check(rows)
    rain = dict(rows)

    wet = max(rows, key=lambda r: r[1])
    dry = min(rows, key=lambda r: r[1])
    print(f"Data check OK: 12 months, sum {total:.1f} mm ({diff:.1f}% from the portal's {PORTAL_ANNUAL_MM} mm)")
    print(f"Wettest month: {wet[0]} ({wet[1]:.1f} mm)   Driest month: {dry[0]} ({dry[1]:.1f} mm)")
    for sid, name, _, months, kind, _ in SEASONS:
        avg = sum(rain[m] for m in months) / len(months)
        print(f"  {name:<20} {len(months)} months, average {avg:6.1f} mm per month")

    seasons_js = ",\n".join(
        '  { id: "%s", name: "%s", localName: "%s", months: [%s], type: "%s", note: "%s" }'
        % (sid, name, local, ", ".join('"%s"' % FULL[m] for m in months), kind, note)
        for sid, name, local, months, kind, note in SEASONS)
    rain_js = ",\n".join('  { month: "%s", mm: %.2f }' % (m, mm) for m, mm in rows)

    OUT_FILE.write_text(
        "// AUTO-GENERATED by build_data.py from rwanda-monthly-rainfall-1991-2020.csv\n"
        "// Do not edit by hand: change the CSV or the script, then run the script again.\n\n"
        f"const rwandaSeasons = [\n{seasons_js}\n];\n\n"
        "const rainfallInfo = {\n"
        '  title: "Average monthly rainfall in Rwanda",\n'
        f'  period: "{PERIOD}",\n  unit: "mm",\n  retrieved: "{RETRIEVED}",\n'
        f'  source: "{SOURCE}",\n  sourceUrl: "{SOURCE_URL}"\n'
        "};\n\n"
        f"const monthlyRainfall = [\n{rain_js}\n];\n",
        encoding="utf-8")
    print(f"Written: {OUT_FILE.name}")


if __name__ == "__main__":
    main()
